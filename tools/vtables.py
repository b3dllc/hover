#!/usr/bin/env python3
"""Audit the original hover.exe's virtual function tables against our build.

Usage (from the repository root, after ./build.sh):

    /workspace/tools/venv/bin/python tools/vtables.py > notes/vtables.md
    /workspace/tools/venv/bin/python tools/vtables.py 0x4ba370   # one table

For every vtable the original's constructors install (a `mov dword ptr
[reg+disp], 0x4Bxxxx` whose immediate lands in the original's .rdata and
points at a run of .text pointers) the report lists each slot that points at
game code - below the library frontier 0x43E400 - together with the function
our build has in the same slot, so that overrides we have not decompiled
show up as MISSING.

How the two sides are lined up:

* The original's table is read straight out of /workspace/hover/hover.exe.
* Our table is found by content: every `??_7Class@@6B@` symbol in
  build/hover.map is a vtable of ours, and the one that carries our
  counterparts of the original's slot functions (via the `// FUNCTION: HOVER
  0x...` markers, resolved the way tools/vc2map.py resolves them) in the same
  slots is the match.  A table with no decompiled slot at all cannot be
  matched and its "ours" column stays "?".
* A class name comes from the matched vtable of ours, else from the
  constructor the table is installed in, else from the CRuntimeClass that the
  table's GetRuntimeClass slot returns - which is what the hand-written name
  corrections notes/vtables.md used to carry did by hand.

This script replaces the one that used to live in the description of the PR
that added notes/vtables.md (it was not recoverable; see the file header).
"""

import bisect
import re
import struct
import sys
from pathlib import Path

from capstone import CS_ARCH_X86, CS_MODE_32, Cs

ROOT = Path(__file__).resolve().parent.parent
ORIG = Path("/workspace/hover/hover.exe")
OURS = ROOT / "build" / "hover.exe"
MAP = ROOT / "build" / "hover.map"

# Everything below this address in the original is game code; above it is
# statically linked MFC/CRT (see notes/coverage.md).
LIBRARY_FRONTIER = 0x43E400
# The original's vtables all live in this window of .rdata.
VTABLE_LO, VTABLE_HI = 0x4BA000, 0x4C4000
# Empty `ret` bodies shared by every class (Serialize/AssertValid/Dump/
# DoDataExchange): not real misses.
EMPTY_BODIES = {0x425360, 0x425370, 0x425380, 0x426E70}
# Tables that belong to MFC even though game constructors install them and
# some of their slots sit below the frontier (linker-placed COMDATs).
# 0x4BB670 is CObject's own vtable: slot 0 returns the "CObject"
# CRuntimeClass at 0x4C6A20, slot 1 (0x429530) is CObject's scalar deleting
# destructor and MFC's own CObArray::CObArray (0x4494EA) stores it too.  It
# was once mistaken for an intermediate game base class (PR #103).
LIBRARY_TABLES = {0x4BB670: "CObject"}


PREAMBLE = """# Virtual function tables of the original hover.exe

Generated by tools/vtables.py (`/workspace/tools/venv/bin/python \
tools/vtables.py > notes/vtables.md`, after ./build.sh - rerun it whenever
classes are decompiled). For every vtable the original's constructors
install, each slot that points at game code (below the library frontier
0x43E400) is listed with the function our build has in the same slot.
**MISSING** means the original overrides a virtual that we have not
decompiled, so our build silently runs the base-class version. The tiny
functions 0x425360/0x425370/0x425380/0x426E70 are empty `ret`s
(Serialize/AssertValid/Dump/DoDataExchange) and are not real misses; tables
all of whose game-code slots are MFC's own internals are left out entirely,
as is 0x4BB670, which is `CObject`'s own vtable even though every game
constructor stores it first (that store is CObject's inlined constructor,
not an intermediate base class - see LIBRARY_TABLES in the script).

Each class name comes from the CRuntimeClass that the table's
GetRuntimeClass slot returns, else from the vtable of ours that carries our
counterparts of the same slots, else from the constructor the table is
installed in - in that order. (The hand-written name corrections this file
used to carry are folded into the tables below; two facts from them that the
tables cannot show are that REGIONNODE is a plain 0x10-byte struct with no
vtable at all, and that CSub406C90 is the unrelated 0x20-byte span-buffer
header with ctor 0x41B870.)

Note also that a **MISSING** row whose original function is a five-byte
`jmp` into the base class' implementation is a *forwarding override*
(`void CDerived::F() { CBase::F(); }`), not a linker thunk - see
notes/perfect-match.md rule 50.
"""


# ---------------------------------------------------------------------------
# PE access


class Image:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        d = self.data
        pe = struct.unpack_from("<I", d, 0x3C)[0]
        nsec = struct.unpack_from("<H", d, pe + 6)[0]
        optsz = struct.unpack_from("<H", d, pe + 20)[0]
        self.base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
        self.sections = []
        for i in range(nsec):
            o = pe + 24 + optsz + 40 * i
            name = d[o : o + 8].rstrip(b"\0").decode("ascii", "replace")
            vsz, va, rsz, raw = struct.unpack_from("<IIII", d, o + 8)
            self.sections.append((name, self.base + va, max(vsz, rsz), raw, rsz))
        self.text_start, self.text = self.section(".text")

    def section(self, name):
        for nm, va, vsz, raw, rsz in self.sections:
            if nm == name:
                return va, self.data[raw : raw + rsz]
        raise RuntimeError(f"{name} not found")

    def offset(self, va):
        for _nm, start, vsz, raw, rsz in self.sections:
            if start <= va < start + vsz:
                off = raw + (va - start)
                return off if off < raw + rsz else None
        return None

    def dword(self, va):
        off = self.offset(va)
        if off is None or off + 4 > len(self.data):
            return None
        return struct.unpack_from("<I", self.data, off)[0]

    def cstr(self, va, limit=64):
        off = self.offset(va)
        if off is None:
            return None
        end = self.data.find(b"\0", off, off + limit)
        if end < 0:
            return None
        try:
            return self.data[off:end].decode("ascii")
        except UnicodeDecodeError:
            return None

    def in_text(self, va):
        return self.text_start <= va < self.text_start + len(self.text)


# ---------------------------------------------------------------------------
# Mangled names


def simplify(mangled):
    """Turn a VC++ 2.x mangled name into something readable."""
    if mangled.startswith("??_E") or mangled.startswith("??_G"):
        cls = mangled[4:].split("@@")[0]
        return f"{cls}::~ (deleting)"
    if mangled.startswith("??_7"):
        cls = mangled[4:].split("@@")[0]
        return f"{cls} vftable"
    if mangled.startswith("??0"):
        cls = mangled[3:].split("@@")[0]
        return f"{cls}::{cls}"
    if mangled.startswith("??1"):
        cls = mangled[3:].split("@@")[0]
        return f"{cls}::~{cls}"
    if mangled.startswith("?"):
        body = mangled[1:].split("@@")[0]
        parts = body.split("@")
        if len(parts) == 1:
            return parts[0]
        return "::".join(reversed(parts[1:])) + "::" + parts[0]
    return mangled.lstrip("_")


# ---------------------------------------------------------------------------
# Our build


def our_symbols():
    """The map's symbols, plus addr -> (mangled name, object file)."""
    sys.path.insert(0, str(ROOT / "tools"))
    import vc2map

    syms = vc2map.parse_map(MAP)
    # parse_map drops the object file, which tells our code from the library.
    objs = {}
    line_re = re.compile(
        r"^\s+[0-9A-Fa-f]{4}:[0-9A-Fa-f]{8}\s+(\S+)\s+[0-9A-Fa-f]{8}\s+"
        r"(?:f\s+)?(\S+)\s*$"
    )
    for line in open(MAP, errors="ignore"):
        m = line_re.match(line)
        if m is not None:
            objs.setdefault(m.group(1), m.group(2))
    by_addr = {}
    for s in syms:
        by_addr.setdefault(s["addr"], (s["name"], objs.get(s["name"], "?")))
    return syms, by_addr


def our_markers(syms):
    """orig addr -> (our addr, display name) for every resolved marker."""
    sys.path.insert(0, str(ROOT / "tools"))
    import vc2map

    markers = vc2map.scan_markers(ROOT / "src")
    vc2map.resolve_markers(markers, syms)
    out = {}
    for m in markers:
        if m["kind"] == "GLOBAL" or "sym" not in m:
            continue
        decl = m["decl"].split("(")[0].strip()
        out[m["orig_addr"]] = (m["sym"]["addr"], decl)
    return out


def our_vtables(ours, syms):
    """[(class name, address, [slot addresses])] for every ??_7 symbol."""
    tables = []
    starts = sorted({s["addr"] for s in syms})
    for s in syms:
        if not s["name"].startswith("??_7"):
            continue
        addr = s["addr"]
        slots = []
        va = addr
        while True:
            if va != addr and va in starts:
                break
            val = ours.dword(va)
            if val is None or not ours.in_text(val):
                break
            slots.append(val)
            va += 4
        tables.append((s["name"][4:].split("@@")[0], addr, slots))
    return tables


# ---------------------------------------------------------------------------
# The original's tables


def find_vtable_stores(orig):
    """{vtable address: [store addresses]} for `mov [mem], 0x4Bxxxx`."""
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    text, start = orig.text, orig.text_start
    stores = {}
    for off in range(0, len(text) - 4):
        val = struct.unpack_from("<I", text, off)[0]
        if not (VTABLE_LO <= val < VTABLE_HI):
            continue
        # The immediate ends the instruction; a `mov dword ptr [...], imm32`
        # is 6 to 10 bytes long, so try each plausible instruction start.
        for back in range(6, 11):
            ins_off = off + 4 - back
            if ins_off < 0:
                continue
            code = text[ins_off : ins_off + back]
            try:
                ins = next(md.disasm(code, start + ins_off))
            except StopIteration:
                continue
            if ins.size != back or ins.mnemonic != "mov":
                continue
            if not ins.op_str.startswith("dword ptr ["):
                continue
            if not ins.op_str.endswith(hex(val)):
                continue
            stores.setdefault(val, []).append(ins.address)
            break
    return stores


def table_slots(orig, addr, others):
    """The run of .text pointers at addr, stopped by the next table."""
    slots = []
    va = addr
    while True:
        if va != addr and va in others:
            break
        val = orig.dword(va)
        if val is None or not orig.in_text(val):
            break
        slots.append(val)
        va += 4
    return slots


def runtime_class_name(orig, slots):
    """The class name from a GetRuntimeClass slot (`mov eax, imm32 / ret`)."""
    if not slots:
        return None
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    off = orig.offset(slots[0])
    if off is None:
        return None
    ins = list(md.disasm(orig.data[off : off + 8], slots[0]))
    if len(ins) < 2 or ins[0].mnemonic != "mov" or not ins[0].op_str.startswith("eax, "):
        return None
    if ins[1].mnemonic != "ret":
        return None
    try:
        rtc = int(ins[0].op_str.split(", ")[1], 16)
    except ValueError:
        return None
    name_ptr = orig.dword(rtc)
    if name_ptr is None:
        return None
    name = orig.cstr(name_ptr)
    if name and re.match(r"^C[A-Za-z_][\w]*$", name):
        return name
    return None


def enclosing_function(addr, markers, starts, sizes):
    """(function address, display name) of the decompiled function that
    contains addr, or None when the store sits in code we have not
    decompiled (the function's extent comes from origsize.py)."""
    i = bisect.bisect_right(starts, addr) - 1
    if i < 0:
        return None
    start = starts[i]
    size = sizes.size(start)
    if size is None or addr >= start + size:
        return None
    return start, markers[start][1]


def class_of(decl):
    """The class of a `Type Class::Method` declaration, if it is a ctor."""
    head = decl.split("::")
    if len(head) != 2:
        return None, None
    cls = head[0].split()[-1].lstrip("~")
    method = head[1]
    return cls, method


# ---------------------------------------------------------------------------


def main():
    only = int(sys.argv[1], 16) if len(sys.argv) > 1 else None

    orig = Image(ORIG)
    ours = Image(OURS)
    syms, by_addr = our_symbols()
    markers = our_markers(syms)
    ourtabs = our_vtables(ours, syms)

    marker_starts = sorted(markers)

    sys.path.insert(0, str(ROOT / "tools"))
    import origsize

    sizes = origsize.OrigSizes(ORIG, marker_starts)

    stores = find_vtable_stores(orig)
    addrs = sorted(stores)

    out = []
    total_missing = 0
    for addr in addrs:
        if only is not None and addr != only:
            continue
        slots = table_slots(orig, addr, set(addrs))
        if not slots:
            continue
        # A table with no game-code slot at all is one of MFC's own, dragged
        # in by the static library; it says nothing about our coverage.
        if not any(
            fn < LIBRARY_FRONTIER and fn not in EMPTY_BODIES for fn in slots
        ):
            continue

        # Our counterpart: the vtable of ours that holds our versions of the
        # original's slot functions in the same slots.
        anchors = {
            i: markers[fn][0] for i, fn in enumerate(slots) if fn in markers
        }
        match, score = None, 0
        if anchors:
            for cls, taddr, tslots in ourtabs:
                hits = sum(
                    1
                    for i, want in anchors.items()
                    if i < len(tslots) and tslots[i] == want
                )
                if hits > score:
                    match, score = (cls, taddr, tslots), hits

        # Where the table is installed: prefer a store we can name.
        ctor = where = None
        for store in stores[addr]:
            found = enclosing_function(store, markers, marker_starts, sizes)
            if found is not None:
                ctor = found
                where = f"ctor {found[0]:#x} {found[1]}"
                break
        if where is None:
            where = f"set at {stores[addr][0]:#x}"

        if addr in LIBRARY_TABLES:
            continue

        # The class name, most reliable source first: the vtable of ours that
        # matched by content, then the constructor the table is installed in,
        # then the CRuntimeClass the GetRuntimeClass slot returns.
        name = None
        if match is not None:
            name = match[0]
        if name is None and ctor is not None:
            cls, method = class_of(ctor[1])
            if cls is not None and method in (cls, "~" + cls):
                name = cls
        if name is None:
            name = runtime_class_name(orig, slots)
        if name is None and ctor is not None:
            name = class_of(ctor[1])[0]
        if name is None:
            name = "unknown class"

        # A table with no decompiled slot cannot be matched by content; if we
        # have a vtable of that class, read our column out of it anyway.
        if match is None:
            for cls, taddr, tslots in ourtabs:
                if cls == name:
                    match = (cls, taddr, tslots)
                    break

        rows = []
        missing = 0
        all_library = True
        for i, fn in enumerate(slots):
            if fn >= LIBRARY_FRONTIER or fn in EMPTY_BODIES:
                continue
            sym = None
            if match is not None and i < len(match[2]):
                sym = by_addr.get(match[2][i])
            if fn in markers:
                status, ourname = "FUNCTION", markers[fn][1]
                if sym is not None and match[2][i] != markers[fn][0]:
                    ourname = simplify(sym[0])
                all_library = False
            else:
                status = "**MISSING**"
                missing += 1
                ourname = simplify(sym[0]) if sym is not None else "?"
                # ":" in the object name means a member of a library
                # (NAFXCW:wingdi.obj); our own code has none.
                if sym is None or ":" not in sym[1]:
                    all_library = False
            rows.append(f"| {i} | {fn:#x} | {ourname} | {status} |")

        # One of MFC's own tables, whose "missing" slots are library
        # internals we would never decompile.
        if rows and all_library:
            continue
        total_missing += missing

        out.append(f"## {name} — vtable {addr:#x} ({len(slots)} slots; {where})")
        if rows:
            out.append("| slot | original | ours (same slot) | status |")
            out.append("|---|---|---|---|")
            out.extend(rows)
        else:
            out.append("all game-code slots decompiled")
        out.append("")

    if only is None:
        print(PREAMBLE)
    print("\n".join(out))
    print(f"\nTotal missing override slots: {total_missing}")


if __name__ == "__main__":
    main()
